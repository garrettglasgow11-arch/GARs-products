FONTS = {False: (F5, 5, 7, 6), True: (F4, 4, 6, 5)}  # data, w, h, advance

_glyph_cache = {}


def _glyph(ch, col, small):
    key = (ch, col, small)
    g = _glyph_cache.get(key)
    if g is not None:
        return g
    data, gw, gh, _ = FONTS[small]
    rows = data.get(ch) or data.get(ch.upper()) or data['?']
    surf = pygame.Surface((gw, gh), pygame.SRCALPHA)
    for y, bits in enumerate(rows):
        for x in range(gw):
            if bits & (1 << (gw - 1 - x)):
                surf.set_at((x, y), col)
    _glyph_cache[key] = surf
    return surf


def text_w(s, small=False, tracking=0):
    _, _, _, adv = FONTS[small]
    return max(0, len(s) * (adv + tracking) - (1 + tracking)) if s else 0


def text_h(small=False):
    return FONTS[small][2]


def text(surf, s, x, y, col, small=False, tracking=0):
    """Draw a string.  Returns the x just past the last glyph."""
    _, _, _, adv = FONTS[small]
    step = adv + tracking
    for i, ch in enumerate(s):
        if ch != ' ':
            surf.blit(_glyph(ch, col, small), (x + i * step, y))
    return x + len(s) * step


def text_c(surf, s, cx, y, col, small=False, tracking=0):
    text(surf, s, cx - text_w(s, small, tracking) // 2, y, col, small, tracking)


def text_sh(surf, s, x, y, col, sh=None, small=False, tracking=0):
    """Text with a 1px drop shadow, for drawing over busy backgrounds."""
    text(surf, s, x + 1, y + 1, sh or COL['ink'], small, tracking)
    text(surf, s, x, y, col, small, tracking)


def text_sh_c(surf, s, cx, y, col, sh=None, small=False, tracking=0):
    text_sh(surf, s, cx - text_w(s, small, tracking) // 2, y, col, sh, small, tracking)


# ── primitives ─────────────────────────────────────────────────────────
def rect(surf, x, y, w, h, col):
    surf.fill(col, (int(x), int(y), int(w), int(h)))


def frame(surf, x, y, w, h, col, t=1):
    x, y, w, h = int(x), int(y), int(w), int(h)
    surf.fill(col, (x, y, w, t))
    surf.fill(col, (x, y + h - t, w, t))
    surf.fill(col, (x, y, t, h))
    surf.fill(col, (x + w - t, y, t, h))


def panel(surf, x, y, w, h, fill='dirt1', edge='dirt3', shade='dirt0'):
    """A chunky bevelled window."""
    x, y, w, h = int(x), int(y), int(w), int(h)
    rect(surf, x + 1, y + 1, w - 2, h - 2, COL[fill] if isinstance(fill, str) else fill)
    frame(surf, x, y, w, h, COL[edge] if isinstance(edge, str) else edge)
    # bevel: light along the top/left, dark along the bottom/right
    rect(surf, x + 1, y + 1, w - 2, 1, COL[shade] if isinstance(shade, str) else shade)
    rect(surf, x + 1, y + h - 2, w - 2, 1, COL['dirt0'])
    # corner notches so it reads as pixel art rather than a plain box
    for cx, cy in ((x, y), (x + w - 1, y), (x, y + h - 1), (x + w - 1, y + h - 1)):
        surf.set_at((cx, cy), COL['dirt0'])


def bar(surf, x, y, w, h, frac, fg, bg='dirt0', edge='dirt3'):
    frac = max(0.0, min(1.0, frac))
    rect(surf, x, y, w, h, COL[bg] if isinstance(bg, str) else bg)
    fw = int(round((w - 2) * frac))
    if fw > 0:
        rect(surf, x + 1, y + 1, fw, h - 2, COL[fg] if isinstance(fg, str) else fg)
    frame(surf, x, y, w, h, COL[edge] if isinstance(edge, str) else edge)


def dither(surf, x, y, w, h, col, step=2):
    """Checkerboard fill — cheap shading that stays pixel-crisp."""
    x, y, w, h = int(x), int(y), int(w), int(h)
    for yy in range(y, y + h):
        for xx in range(x + (yy % step), x + w, step):
            if 0 <= xx < surf.get_width() and 0 <= yy < surf.get_height():
                surf.set_at((xx, yy), col)


def vignette(surf, strength=90):
    """Darken the edges of the frame."""
    w, h = surf.get_size()
    band = pygame.Surface((w, h), pygame.SRCALPHA)
    steps = 10
    for i in range(steps):
        a = int(strength * (i + 1) / steps)
        m = steps - i
        pygame.draw.rect(band, (0, 0, 0, a // steps + 1), (m, m, w - 2 * m, h - 2 * m), 1)
    surf.blit(band, (0, 0))
